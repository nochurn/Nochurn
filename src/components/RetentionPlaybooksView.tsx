import React, { useState } from 'react';
import {
  Sparkles,
  Copy,
  Check,
  Clock,
  TrendingUp,
  UserCheck,
  AlertTriangle,
  ExternalLink,
  MessageSquare,
  ShieldCheck,
  FileText,
  DollarSign
} from 'lucide-react';
import { Customer } from '../types';
import { formatCurrency, getRiskColorClass } from '../utils/formatters';

interface RetentionPlaybooksViewProps {
  customers: Customer[];
  onSelectCustomer: (cust: Customer) => void;
  onRunAiRecommend: (id: string) => Promise<void>;
  onMarkSaved: (id: string, notes?: string) => Promise<void>;
  isAiLoading: boolean;
}

export const RetentionPlaybooksView: React.FC<RetentionPlaybooksViewProps> = ({
  customers,
  onSelectCustomer,
  onRunAiRecommend,
  onMarkSaved,
  isAiLoading
}) => {
  const [filterCategory, setFilterCategory] = useState<'all' | 'critical' | 'high'>('all');
  const [copiedId, setCopiedId] = useState<string | null>(null);

  // Focus only on at-risk customers (Score 61+)
  const atRisk = customers.filter((c) => {
    if (filterCategory === 'critical') return c.riskScore >= 86;
    if (filterCategory === 'high') return c.riskScore >= 61 && c.riskScore < 86;
    return c.riskScore >= 61;
  });

  const handleCopy = (id: string, text: string) => {
    navigator.clipboard.writeText(text);
    setCopiedId(id);
    setTimeout(() => setCopiedId(null), 2500);
  };

  return (
    <div className="space-y-6">
      {/* Header */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-3 bg-white p-5 rounded-xl border border-gray-200 shadow-xs">
        <div>
          <div className="flex items-center gap-2">
            <h2 className="text-xl font-bold text-gray-900">Gemini Retention Playbooks</h2>
            <span className="text-xs font-semibold bg-orange-100 text-orange-800 px-2 py-0.5 rounded-full">
              {atRisk.length} High-Risk Accounts
            </span>
          </div>
          <p className="text-xs text-gray-700 mt-1">
            Personalized interventions, copy-paste email scripts, and recovery probabilities generated by Gemini AI.
          </p>
        </div>

        <div className="flex items-center gap-2">
          <button
            onClick={() => setFilterCategory('all')}
            className={`px-3 py-1.5 rounded-lg text-xs font-semibold transition-colors ${
              filterCategory === 'all'
                ? 'bg-blue-900 text-white'
                : 'bg-gray-100 text-gray-700 hover:bg-gray-200'
            }`}
          >
            All At-Risk ({customers.filter(c => c.riskScore >= 61).length})
          </button>
          <button
            onClick={() => setFilterCategory('critical')}
            className={`px-3 py-1.5 rounded-lg text-xs font-semibold transition-colors ${
              filterCategory === 'critical'
                ? 'bg-red-600 text-white'
                : 'bg-red-50 text-red-700 hover:bg-red-100 border border-red-200'
            }`}
          >
            Critical Only (86+)
          </button>
          <button
            onClick={() => setFilterCategory('high')}
            className={`px-3 py-1.5 rounded-lg text-xs font-semibold transition-colors ${
              filterCategory === 'high'
                ? 'bg-orange-600 text-white'
                : 'bg-orange-50 text-orange-700 hover:bg-orange-100 border border-orange-200'
            }`}
          >
            High Risk (61-85)
          </button>
        </div>
      </div>

      {/* Playbook Cards Grid */}
      <div className="grid grid-cols-1 md:grid-cols-2 gap-5">
        {atRisk.length === 0 ? (
          <div className="col-span-2 p-12 text-center bg-white rounded-xl border border-gray-200">
            <ShieldCheck className="w-10 h-10 text-emerald-500 mx-auto mb-2" />
            <h4 className="text-sm font-bold text-gray-900">Zero Critical Customers in this view!</h4>
            <p className="text-xs text-gray-700 mt-1">All monitored accounts are within healthy retention thresholds.</p>
          </div>
        ) : (
          atRisk.map((cust) => {
            const riskClasses = getRiskColorClass(cust.riskCategory);
            const script = cust.retentionRecommendation?.emailScript ||
              `Subject: Urgent check-in regarding ${cust.name}'s account\n\nHi ${cust.name.split(' ')[0]},\n\nI noticed your account has faced some friction recently and wanted to personally step in. Can we connect today for 10 minutes?\n\nBest,\nAlex Vance\nFounder & CEO, ChurnShield AI`;

            return (
              <div
                key={cust.id}
                className="bg-white rounded-xl border border-gray-200 shadow-xs flex flex-col justify-between overflow-hidden hover:border-blue-300 transition-all"
              >
                {/* Header */}
                <div className="p-4 border-b border-gray-100 bg-gray-50/60">
                  <div className="flex items-start justify-between">
                    <div>
                      <div className="flex items-center gap-2">
                        <h4 className="font-bold text-sm text-gray-900">{cust.name}</h4>
                        <span className={`px-2 py-0.5 rounded-full text-[10px] font-bold ${riskClasses.badge}`}>
                          Score {cust.riskScore} • {cust.riskCategory}
                        </span>
                        {cust.status === 'saved' && (
                          <span className="text-[10px] bg-emerald-100 text-emerald-800 px-2 py-0.5 rounded-full font-bold">
                            Saved
                          </span>
                        )}
                      </div>
                      <p className="text-[11px] text-gray-700 mt-0.5">
                        {cust.companyDomain} • {formatCurrency(cust.mrr)} MRR • {cust.plan} Plan
                      </p>
                    </div>

                    <button
                      onClick={() => onSelectCustomer(cust)}
                      className="text-xs font-semibold text-blue-900 hover:underline flex items-center gap-1"
                    >
                      Full Details <ExternalLink className="w-3 h-3" />
                    </button>
                  </div>

                  {/* Recommended Action Pill */}
                  <div className="mt-3 p-2.5 bg-blue-50/70 rounded-lg border border-blue-100 flex items-center justify-between text-xs">
                    <span className="font-semibold text-blue-950 truncate max-w-[280px]">
                      {cust.recommendedAction || cust.retentionRecommendation?.action || 'Executive Outreach'}
                    </span>
                    <button
                      onClick={() => onRunAiRecommend(cust.id)}
                      disabled={isAiLoading}
                      title="Regenerate strategy with Gemini"
                      className="text-[10px] text-blue-900 hover:text-blue-950 font-bold flex items-center gap-1 shrink-0 ml-2"
                    >
                      <Sparkles className="w-3 h-3 text-blue-800" />
                      Regenerate
                    </button>
                  </div>
                </div>

                {/* Metrics Stats */}
                <div className="grid grid-cols-3 divide-x divide-gray-100 border-b border-gray-100 text-center py-2 bg-white">
                  <div>
                    <span className="text-[10px] text-gray-700 font-medium">Recovery Rate</span>
                    <div className="text-sm font-bold text-emerald-600">
                      {cust.retentionRecommendation?.recoveryProbability ?? 35}%
                    </div>
                  </div>
                  <div>
                    <span className="text-[10px] text-gray-700 font-medium">Effort Time</span>
                    <div className="text-sm font-bold text-blue-900">
                      {cust.retentionRecommendation?.effortMinutes ?? 30} min
                    </div>
                  </div>
                  <div>
                    <span className="text-[10px] text-gray-700 font-medium">MRR at Risk</span>
                    <div className="text-sm font-bold text-red-600">
                      {formatCurrency(cust.mrr)}
                    </div>
                  </div>
                </div>

                {/* Email Script Preview */}
                <div className="p-4 space-y-2 flex-1">
                  <div className="flex items-center justify-between text-[11px] text-gray-700 font-semibold">
                    <span className="flex items-center gap-1.5">
                      <FileText className="w-3.5 h-3.5 text-blue-900" />
                      Personalized Founder Script:
                    </span>
                    <button
                      onClick={() => handleCopy(cust.id, script)}
                      className="text-xs font-semibold text-blue-900 hover:text-blue-950 flex items-center gap-1"
                    >
                      {copiedId === cust.id ? (
                        <>
                          <Check className="w-3.5 h-3.5 text-emerald-600" />
                          <span className="text-emerald-700">Copied!</span>
                        </>
                      ) : (
                        <>
                          <Copy className="w-3.5 h-3.5 text-gray-400" />
                          <span>Copy</span>
                        </>
                      )}
                    </button>
                  </div>

                  <div className="p-3 bg-gray-50 rounded-lg text-xs font-mono text-gray-700 max-h-36 overflow-y-auto leading-relaxed whitespace-pre-wrap border border-gray-200/60">
                    {script}
                  </div>
                </div>

                {/* Bottom Action Footer */}
                <div className="p-3 bg-gray-50 border-t border-gray-100 flex items-center justify-between">
                  <span className="text-[11px] text-gray-700">
                    Channel: <strong>{cust.retentionRecommendation?.suggestedChannel || 'Email'}</strong>
                  </span>

                  {cust.status !== 'saved' ? (
                    <button
                      onClick={() => onMarkSaved(cust.id, 'Executed retention email & offered custom concession')}
                      className="px-3 py-1.5 bg-emerald-600 hover:bg-emerald-700 text-white rounded-lg text-xs font-bold flex items-center gap-1.5 shadow-xs transition-colors"
                    >
                      <UserCheck className="w-3.5 h-3.5" />
                      Mark Saved (+{formatCurrency(cust.mrr)})
                    </button>
                  ) : (
                    <span className="text-xs font-bold text-emerald-700 flex items-center gap-1">
                      <Check className="w-4 h-4 text-emerald-600" />
                      Retained
                    </span>
                  )}
                </div>
              </div>
            );
          })
        )}
      </div>
    </div>
  );
};
